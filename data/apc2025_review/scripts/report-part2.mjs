  p('- **استنتاجات الوكيل (تحت إقراركم):** تصنيف كل مادة إلى (مثبت/مرشح/تعارض/بلا دليل)، ووصف سبب عدم الحسم في (ج)، وقائمة الحيوي المحتمل في (د)، وجدول تقاطعات المحاصيل في (هـ/13).');
  p();
