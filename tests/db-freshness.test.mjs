import fs from 'node:fs';
import { evaluate, INTERNATIONAL, EXCLUDED, CYCLE_DAYS } from '../scripts/db-freshness.mjs';
let pass = 0, fail = 0;
const ok = (n, c, d) => { c ? pass++ : fail++; console.log((c ? '  PASS ' : '  FAIL ') + n + (d ? ' — ' + d : '')); };
const dc = { 'libya-248': '2020-01-01', 'libya-500': '2020-01-01', eu: '2026-11-01', epa: '2026-11-01', 'epa-cancelled': '2026-11-01', canada: '2026-10-10', australia: '2026-11-01' };
const r = evaluate(dc, '2026-11-10');
ok('cycle is 15 days', CYCLE_DAYS === 15);
ok('Libya never evaluated, however old', !r.rows.some(x => /libya/.test(x.db)) && EXCLUDED.length === 2);
ok('all five international DBs evaluated', r.rows.length === 5 && INTERNATIONAL.length === 5);
ok('31-day-old canada is stale; others fresh', r.stale.join() === 'canada', r.stale.join());
ok('exactly 15 days is still fresh', evaluate({ ...dc, canada: '2026-10-26' }, '2026-11-10').stale.length === 0);
ok('16 days is stale', evaluate({ ...dc, canada: '2026-10-25' }, '2026-11-10').stale.join() === 'canada');
ok('missing date counts as stale', evaluate({}, '2026-11-10').stale.length === 5);
const vj = JSON.parse(fs.readFileSync('version.json', 'utf8'));
ok('version.json carries all international dates', INTERNATIONAL.every(k => vj.dataCheck[k]));
const wf = fs.readFileSync('.github/workflows/db-refresh.yml', 'utf8');
ok('workflow is scheduled twice a month (1st,16th)', /cron: "0 3 1,16 \* \*"/.test(wf));
ok('workflow never merges or deploys', !/gh pr merge|wrangler|pages deploy|--auto/.test(wf));
ok('workflow does not touch Libya files', !/libya/.test(wf.replace(/#.*$/gm, '')));
console.log(pass + ' pass / ' + fail + ' fail'); process.exit(fail ? 1 : 0);
